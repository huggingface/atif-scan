"use strict";
const assert = require("node:assert/strict");
const E = require("./evidence.js");
const demo = require("./fixture.js");
const first = demo.trials[0], finding = first.findings[0];
const ref = finding.anchors[finding.primary].ref;
const field = E.locate(first, ref).field;
const offset = E.focusOffset(field, ref);
assert.ok(offset > 6000, "Evidence is deliberately beyond the first default inspection page.");
assert.ok(E.page(field, offset).text.includes("DEMO SOURCE REFERENCE"));
assert.equal(E.page(field, offset).text.length <= E.PAGE_SIZE, true);
assert.deepEqual(E.context(first, 70).map(s => s.id), [45, 55, 70, 90, 110]);
assert.throws(() => E.context(first, 71), /Unknown step/);
assert.throws(() => E.locate(first, { step: 70, part: "missing" }), /Unknown field/);
assert.throws(() => E.page(field, -1), /Invalid masked offset/);
assert.throws(() => E.page(field, 0, 6001), /Invalid page size/);
const unicode = { text: "🙂İ🙂needle end", status: "text" };
assert.deepEqual(E.literalMatches(unicode.text, "needle"), [{ start: 3, end: 9 }]);
assert.equal(E.page(unicode, 3, 6).text, "needle");
assert.equal(E.page(unicode, 0, 2).text, "🙂İ");
assert.throws(() => E.literalMatches("text", ""), /1–150/);
assert.throws(() => E.literalMatches("text", "x".repeat(151)), /1–150/);
assert.equal(E.literalMatches("needle ".repeat(60), "needle", 40).length, 40);
assert.equal(E.search(first, "DEMO SOURCE REFERENCE").length, 2);
assert.equal(E.search(first, "demo source reference").length, 0, "Literal search is explicitly case-sensitive.");
for (const trial of demo.trials) {
  for (const f of trial.findings) for (const a of f.anchors) E.locate(trial, a.ref);
  for (const r of trial.review.citations) E.locate(trial, r);
}
const absent = E.locate(demo.trials[1], demo.trials[1].findings[0].anchors[1].ref).field;
assert.equal(E.page(absent, 0).status, "absent");
assert.equal(E.page(absent, 0).text, "");
assert.equal(E.page(absent, 0).next, null);
console.log("Evidence navigation, deep paging, Unicode offsets and unavailable content: PASS");
